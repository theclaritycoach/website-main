/**
 * Turns the human-editable YAML files in supabase/seed-data into SQL.
 *
 *   supabase/seed-data/catalog.yaml        -> supabase/seed.sql
 *   supabase/seed-data/sample-people.yaml  -> supabase/sample-data.sql
 *   (plus docs/SEED-REVIEW.md, a readable list for review)
 *
 * The generated SQL is safe to run again and again: it updates existing rows
 * by slug and hides (active = false) anything you removed from the YAML.
 *
 * Run:  npm run seed:build
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { parse } from "yaml";

const root = join(dirname(new URL(import.meta.url).pathname), "..");
const read = (p: string) => parse(readFileSync(join(root, p), "utf8"));

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

export function slugify(s: string): string {
  return s
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function q(v: unknown): string {
  if (v === null || v === undefined || v === "") return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

function arr(values: string[] | undefined): string {
  if (!values || values.length === 0) return "'{}'::text[]";
  return `array[${values.map(q).join(", ")}]::text[]`;
}

function uuidFrom(key: string): string {
  const h = createHash("sha1").update(`cce-sample:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

function fail(msg: string): never {
  throw new Error(`Seed data problem: ${msg}`);
}

// ---------------------------------------------------------------------------
// Catalog
// ---------------------------------------------------------------------------

type RoleY = { slug: string; name: string; description?: string; skills?: string[] };
type PracticeY = { slug: string; name: string; description?: string; is_cross_practice?: boolean; roles: RoleY[] };
type CertY = {
  slug: string; name: string; issuer: string; code?: string; tier: string;
  display_priority?: number; roles?: string[]; notes?: string; official_url?: string;
  approx_cost?: string; needs_verification?: boolean; last_verified?: string;
};

const catalog = read("supabase/seed-data/catalog.yaml");
const practices: PracticeY[] = catalog.practices;
const shared: string[] = catalog.shared_skills ?? [];
const certs: CertY[] = catalog.certifications;
const options: Record<string, Record<string, string>> = catalog.options;

const roleSlugs = new Set<string>();
const roleToPractice = new Map<string, string>();
const skills = new Map<string, { name: string; shared: boolean; sort: number }>();
const roleSkillPairs: [string, string][] = [];

let skillSort = 0;
for (const name of shared) {
  const slug = slugify(name);
  skills.set(slug, { name, shared: true, sort: skillSort++ });
}
for (const p of practices) {
  for (const r of p.roles) {
    if (roleSlugs.has(r.slug)) fail(`role slug "${r.slug}" is used twice`);
    roleSlugs.add(r.slug);
    roleToPractice.set(r.slug, p.slug);
    for (const s of shared) roleSkillPairs.push([r.slug, slugify(s)]);
    for (const name of r.skills ?? []) {
      const slug = slugify(name);
      if (!skills.has(slug)) skills.set(slug, { name, shared: false, sort: skillSort++ });
      roleSkillPairs.push([r.slug, slug]);
    }
  }
}
for (const c of certs) {
  if (!["baseline", "role_recommended", "specialist"].includes(c.tier)) fail(`certification "${c.slug}" has unknown tier "${c.tier}"`);
  for (const r of c.roles ?? []) if (!roleSlugs.has(r)) fail(`certification "${c.slug}" links unknown role "${r}"`);
}

const out: string[] = [];
out.push("-- GENERATED by scripts/build-seed.ts from supabase/seed-data/catalog.yaml. Do not edit by hand.");
out.push("begin;");

// Practices
out.push("\n-- Practices");
out.push(
  `insert into public.practices (slug, name, description, sort, is_cross_practice, active) values\n` +
    practices.map((p, i) => `  (${q(p.slug)}, ${q(p.name)}, ${q(p.description)}, ${i}, ${!!p.is_cross_practice}, true)`).join(",\n") +
    `\non conflict (slug) do update set name = excluded.name, description = excluded.description, sort = excluded.sort, is_cross_practice = excluded.is_cross_practice, active = true;`,
);
out.push(`update public.practices set active = false where slug not in (${practices.map((p) => q(p.slug)).join(", ")});`);

// Roles
out.push("\n-- Roles");
const roleRows: string[] = [];
practices.forEach((p) =>
  p.roles.forEach((r, i) => roleRows.push(`  (${q(p.slug)}, ${q(r.slug)}, ${q(r.name)}, ${q(r.description)}, ${i})`)),
);
out.push(
  `insert into public.roles (practice_id, slug, name, description, sort, active)\nselect p.id, v.slug, v.name, v.description, v.sort, true from (values\n${roleRows.join(",\n")}\n) v(practice_slug, slug, name, description, sort)\njoin public.practices p on p.slug = v.practice_slug\non conflict (slug) do update set practice_id = excluded.practice_id, name = excluded.name, description = excluded.description, sort = excluded.sort, active = true;`,
);
out.push(`update public.roles set active = false where slug not in (${[...roleSlugs].map(q).join(", ")});`);

// Skills
out.push("\n-- Skills");
out.push(
  `insert into public.skills (slug, name, is_shared, sort, active) values\n` +
    [...skills.entries()].map(([slug, s]) => `  (${q(slug)}, ${q(s.name)}, ${s.shared}, ${s.sort}, true)`).join(",\n") +
    `\non conflict (slug) do update set name = excluded.name, is_shared = excluded.is_shared, sort = excluded.sort, active = true;`,
);
out.push(`update public.skills set active = false where slug not in (${[...skills.keys()].map(q).join(", ")});`);

out.push("\n-- Role to skill links (rebuilt each time)");
out.push("delete from public.role_skills;");
out.push(
  `insert into public.role_skills (role_id, skill_id)\nselect r.id, s.id from (values\n${roleSkillPairs.map(([r, s]) => `  (${q(r)}, ${q(s)})`).join(",\n")}\n) v(role_slug, skill_slug)\njoin public.roles r on r.slug = v.role_slug\njoin public.skills s on s.slug = v.skill_slug\non conflict do nothing;`,
);

// Certifications
out.push("\n-- Certifications (every seeded certification needs verification)");
out.push(
  `insert into public.certifications (slug, name, issuer, code, tier, official_url, approx_cost, last_verified, needs_verification, display_priority, notes, active) values\n` +
    certs
      .map(
        (c) =>
          `  (${q(c.slug)}, ${q(c.name)}, ${q(c.issuer)}, ${q(c.code)}, ${q(c.tier)}, ${q(c.official_url)}, ${q(c.approx_cost)}, ${c.last_verified ? `${q(c.last_verified)}::date` : "null"}, ${c.needs_verification ?? true}, ${c.display_priority ?? 100}, ${q(c.notes)}, true)`,
      )
      .join(",\n") +
    `\non conflict (slug) do update set name = excluded.name, issuer = excluded.issuer, code = excluded.code, tier = excluded.tier, official_url = excluded.official_url, approx_cost = excluded.approx_cost, last_verified = excluded.last_verified, needs_verification = excluded.needs_verification, display_priority = excluded.display_priority, notes = excluded.notes, active = true;`,
);
out.push(`update public.certifications set active = false where slug not in (${certs.map((c) => q(c.slug)).join(", ")});`);
const certRolePairs = certs.flatMap((c) => (c.roles ?? []).map((r) => [c.slug, r] as const));
out.push("delete from public.certification_roles;");
out.push("delete from public.certification_practices;");
if (certRolePairs.length) {
  const values = certRolePairs.map(([c, r]) => `  (${q(c)}, ${q(r)})`).join(",\n");
  out.push(
    `insert into public.certification_roles (certification_id, role_id)\nselect c.id, r.id from (values\n${values}\n) v(cert_slug, role_slug)\njoin public.certifications c on c.slug = v.cert_slug\njoin public.roles r on r.slug = v.role_slug\non conflict do nothing;`,
  );
  out.push(
    `insert into public.certification_practices (certification_id, practice_id)\nselect distinct cr.certification_id, r.practice_id from public.certification_roles cr join public.roles r on r.id = cr.role_id\non conflict do nothing;`,
  );
}

// Options
out.push("\n-- Dropdown and checklist options");
const optionRows: string[] = [];
for (const [setKey, values] of Object.entries(options)) {
  Object.entries(values).forEach(([value, label], i) => optionRows.push(`  (${q(setKey)}, ${q(String(value))}, ${q(label)}, ${i}, true)`));
}
out.push(
  `insert into public.option_sets (set_key, value, label, sort, active) values\n${optionRows.join(",\n")}\non conflict (set_key, value) do update set label = excluded.label, sort = excluded.sort, active = true;`,
);
out.push(
  `update public.option_sets set active = false where (set_key, value) not in (${Object.entries(options)
    .flatMap(([k, v]) => Object.keys(v).map((val) => `(${q(k)}, ${q(String(val))})`))
    .join(", ")});`,
);

// Statuses
out.push("\n-- Statuses");
out.push(
  `insert into public.statuses (key, label, description, sort, is_terminal) values\n` +
    catalog.statuses
      .map((s: { key: string; label: string; description?: string; is_terminal?: boolean }, i: number) =>
        `  (${q(s.key)}, ${q(s.label)}, ${q(s.description)}, ${i}, ${!!s.is_terminal})`)
      .join(",\n") +
    `\non conflict (key) do update set label = excluded.label, description = excluded.description, sort = excluded.sort, is_terminal = excluded.is_terminal;`,
);

// Scorecards
out.push("\n-- Scorecard criteria");
const scRows: string[] = [];
for (const [type, labels] of Object.entries(catalog.scorecards as Record<string, string[]>)) {
  labels.forEach((label, i) => scRows.push(`  (${q(type)}, ${q(slugify(label))}, ${q(label)}, ${i}, true)`));
}
out.push(
  `insert into public.scorecard_criteria (scorecard_type, key, label, sort, active) values\n${scRows.join(",\n")}\non conflict (scorecard_type, key) do update set label = excluded.label, sort = excluded.sort, active = true;`,
);

// Onboarding
out.push("\n-- Onboarding checklist steps");
out.push(
  `insert into public.onboarding_step_templates (key, label, sort, active) values\n` +
    (catalog.onboarding_steps as string[]).map((l, i) => `  (${q(slugify(l))}, ${q(l)}, ${i}, true)`).join(",\n") +
    `\non conflict (key) do update set label = excluded.label, sort = excluded.sort, active = true;`,
);
out.push(
  `update public.onboarding_step_templates set active = false where key not in (${(catalog.onboarding_steps as string[]).map((l) => q(slugify(l))).join(", ")});`,
);

// Settings
out.push("\n-- Settings");
const settingRows: string[] = [
  `  ('network_name', ${q(JSON.stringify(catalog.network.name))}::jsonb, 'Public name of the network')`,
  `  ('tagline', ${q(JSON.stringify(catalog.network.tagline))}::jsonb, 'Tagline on public pages')`,
  `  ('public_base_url', ${q(JSON.stringify(catalog.network.public_base_url))}::jsonb, 'Public address of the site')`,
];
for (const [key, s] of Object.entries(catalog.settings as Record<string, { value: unknown; description: string }>)) {
  settingRows.push(`  (${q(key)}, ${q(JSON.stringify(s.value))}::jsonb, ${q(s.description)})`);
}
out.push(
  `insert into public.settings (key, value, description) values\n${settingRows.join(",\n")}\non conflict (key) do update set value = excluded.value, description = excluded.description, updated_at = now();`,
);

// Admins
out.push("\n-- Admin allowlist (adds only; deactivate admins in the database)");
out.push(
  `insert into public.admins (email) values ${(catalog.admins as string[]).map((e) => `(${q(e)})`).join(", ")}\non conflict (email) do update set active = true;`,
);

out.push("\ncommit;\n");
writeFileSync(join(root, "supabase/seed.sql"), out.join("\n"));

// ---------------------------------------------------------------------------
// Sample people
// ---------------------------------------------------------------------------

type CertRef = { slug?: string; name?: string; year_earned?: number; state?: string; target_in_days?: number };
type WorkY = { company: string; title?: string; start?: string; end?: string; industry?: string; description?: string };
type PersonY = {
  email: string; full_name: string; city?: string; state?: string; time_zone?: string; status: string;
  applicant_type?: string; firm?: string; total_years?: number; consulting_years?: number;
  primary_practice: string; secondary_practice?: string;
  self_qualified?: string[]; aspiration?: string[]; assigned?: string[];
  skills?: Record<string, number>; tools?: string[]; industries?: string[]; client_types?: string[];
  ai_usage_frequency?: string; hours_per_week?: string; start_in_days?: number;
  engagement_types?: string[]; work_settings?: string[]; travel_frequency?: string;
  gov_subcontractor?: boolean; certifications?: CertRef[]; work_history?: WorkY[];
};

const sample = read("supabase/seed-data/sample-people.yaml");
const statusKeys = new Set((catalog.statuses as { key: string }[]).map((s) => s.key));
const certSlugs = new Map(certs.map((c) => [c.slug, c]));
const practiceSlugs = new Set(practices.map((p) => p.slug));

function checkOptions(who: string, setKey: string, values: string[] | string | undefined) {
  if (values === undefined) return;
  for (const v of Array.isArray(values) ? values : [values]) {
    if (!(String(v) in options[setKey])) fail(`${who}: "${v}" is not a valid ${setKey} option`);
  }
}
function checkRoles(who: string, list?: string[]) {
  for (const r of list ?? []) if (!roleSlugs.has(r)) fail(`${who}: unknown role "${r}"`);
}

const s: string[] = [];
s.push("-- GENERATED by scripts/build-seed.ts from supabase/seed-data/sample-people.yaml. Do not edit by hand.");
s.push("-- SAMPLE DATA ONLY. Remove before launch with: npm run sample:remove");
s.push("begin;");
s.push("select set_config('app.actor_email', 'sample-data', true);");
s.push("delete from public.people where is_sample;");
s.push("delete from public.firms where is_sample;");

const firmIds = new Map<string, string>();
for (const f of sample.firms ?? []) {
  const id = uuidFrom(`firm:${f.key}`);
  firmIds.set(f.key, id);
  checkOptions(`firm ${f.key}`, "team_size", f.team_size);
  checkOptions(`firm ${f.key}`, "business_certs", f.business_certs);
  checkRoles(`firm ${f.key}`, f.services);
  s.push(
    `insert into public.firms (id, name, website, team_size, years_in_business, business_certs, is_sample) values (${q(id)}, ${q(f.name)}, ${q(f.website)}, ${q(f.team_size)}, ${f.years_in_business ?? "null"}, ${arr(f.business_certs)}, true);`,
  );
  for (const r of f.services ?? []) {
    s.push(`insert into public.firm_services (firm_id, role_id) select ${q(id)}, id from public.roles where slug = ${q(r)};`);
  }
}

const people: PersonY[] = sample.people;
people.forEach((p, idx) => {
  const who = p.email;
  if (!p.full_name.endsWith("(Sample)")) fail(`${who}: sample names must end in "(Sample)"`);
  if (!statusKeys.has(p.status)) fail(`${who}: unknown status "${p.status}"`);
  if (!practiceSlugs.has(p.primary_practice)) fail(`${who}: unknown practice "${p.primary_practice}"`);
  if (p.secondary_practice && !practiceSlugs.has(p.secondary_practice)) fail(`${who}: unknown practice "${p.secondary_practice}"`);
  checkRoles(who, p.self_qualified);
  checkRoles(who, p.aspiration);
  checkRoles(who, p.assigned);
  checkOptions(who, "time_zones", p.time_zone);
  checkOptions(who, "tools", p.tools);
  checkOptions(who, "industries", p.industries);
  checkOptions(who, "client_types", p.client_types);
  checkOptions(who, "ai_usage_frequency", p.ai_usage_frequency);
  checkOptions(who, "hours_per_week", p.hours_per_week);
  checkOptions(who, "engagement_types", p.engagement_types);
  checkOptions(who, "work_settings", p.work_settings);
  checkOptions(who, "travel_frequency", p.travel_frequency);

  const id = uuidFrom(`person:${p.email}`);
  const firmId = p.firm ? firmIds.get(p.firm) ?? fail(`${who}: unknown firm "${p.firm}"`) : null;
  const daysAgo = 3 + idx * 6;

  s.push(`\n-- ${p.full_name}`);
  s.push(
    `insert into public.people (id, email, full_name, city, state, time_zone, linkedin_url, applicant_type, firm_id, hear_about, total_years, consulting_years, gov_subcontractor, industries, client_types, tools, ai_usage_frequency, hours_per_week, earliest_start, engagement_types, work_settings, travel_frequency, operating_as, can_provide_w9, nda_ok, has_conflict, ai_cert_commitment, fit_problem, consent_accurate, consent_storage, consent_contact, consented_at, status, first_submitted_at, last_submitted_at, last_profile_update_at, is_sample) values (` +
      [
        q(id), q(p.email), q(p.full_name), q(p.city), q(p.state), q(p.time_zone),
        q(`https://www.linkedin.com/in/sample-${slugify(p.full_name)}`),
        q(p.applicant_type ?? "individual"), firmId ? q(firmId) : "null", q("linkedin"),
        p.total_years ?? "null", p.consulting_years ?? "null", p.gov_subcontractor ?? "null",
        arr(p.industries), arr(p.client_types), arr(p.tools), q(p.ai_usage_frequency), q(p.hours_per_week),
        p.start_in_days !== undefined ? `current_date + ${p.start_in_days}` : "null",
        arr(p.engagement_types), arr(p.work_settings), q(p.travel_frequency),
        q("entity"), "true", "true", "false", q("yes"),
        q("Sample answer for testing."),
        "true", "true", "true", `now() - interval '${daysAgo} days'`,
        q("applied"),
        `now() - interval '${daysAgo} days'`, `now() - interval '${daysAgo} days'`, `now() - interval '${daysAgo} days'`,
        "true",
      ].join(", ") +
      ");",
  );
  if (firmId && p.applicant_type === "firm_contact") {
    s.push(`update public.firms set primary_contact_person_id = ${q(id)} where id = ${q(firmId)};`);
  }
  s.push(`insert into public.person_practices (person_id, practice_id, rank) select ${q(id)}, id, 'primary' from public.practices where slug = ${q(p.primary_practice)};`);
  if (p.secondary_practice) {
    s.push(`insert into public.person_practices (person_id, practice_id, rank) select ${q(id)}, id, 'secondary' from public.practices where slug = ${q(p.secondary_practice)};`);
  }
  for (const kind of ["self_qualified", "aspiration", "assigned"] as const) {
    for (const r of p[kind] ?? []) {
      s.push(`insert into public.person_roles (person_id, role_id, kind) select ${q(id)}, id, ${q(kind)} from public.roles where slug = ${q(r)};`);
    }
  }
  for (const [skillName, level] of Object.entries(p.skills ?? {})) {
    const slug = slugify(skillName);
    if (!skills.has(slug)) fail(`${who}: skill "${skillName}" is not in the catalog`);
    if (![1, 2, 3, 4].includes(level)) fail(`${who}: proficiency for "${skillName}" must be 1 to 4`);
    s.push(`insert into public.person_skills (person_id, skill_id, proficiency, source) select ${q(id)}, id, ${level}, 'applicant' from public.skills where slug = ${q(slug)};`);
  }
  (p.work_history ?? []).forEach((w, i) => {
    const [sy, sm] = (w.start ?? "").split("-").map(Number);
    const current = w.end === "current";
    const [ey, em] = current || !w.end ? [null, null] : w.end.split("-").map(Number);
    if (w.industry) checkOptions(who, "industries", w.industry);
    s.push(
      `insert into public.work_history (person_id, sort, company, title, start_month, start_year, end_month, end_year, is_current, industry, description, from_resume) values (${q(id)}, ${i}, ${q(w.company)}, ${q(w.title)}, ${sm || "null"}, ${sy || "null"}, ${em ?? "null"}, ${ey ?? "null"}, ${current}, ${q(w.industry)}, ${q(w.description)}, true);`,
    );
  });
  for (const c of p.certifications ?? []) {
    const cat = c.slug ? certSlugs.get(c.slug) ?? fail(`${who}: unknown certification "${c.slug}"`) : null;
    const state = c.state ?? "earned";
    s.push(
      `insert into public.person_certifications (person_id, certification_id, name_text, issuer, year_earned, state, target_date) values (${q(id)}, ${cat ? `(select id from public.certifications where slug = ${q(c.slug)})` : "null"}, ${q(cat?.name ?? c.name)}, ${q(cat?.issuer)}, ${c.year_earned ?? "null"}, ${q(state)}, ${c.target_in_days !== undefined ? `current_date + ${c.target_in_days}` : "null"});`,
    );
  }
  if (p.status !== "applied") {
    s.push(`update public.people set status = ${q(p.status)} where id = ${q(id)};`);
  }
});

s.push("\ncommit;\n");
writeFileSync(join(root, "supabase/sample-data.sql"), s.join("\n"));


const md: string[] = [];
md.push("# Seeded catalog, for review");
md.push("");
md.push("Generated from `supabase/seed-data/catalog.yaml` by `npm run seed:build`. Edit the YAML, not this file.");
md.push("");
md.push(`**Totals:** ${practices.length} practice groups, ${roleSlugs.size} roles, ${skills.size} unique skills, ${certs.length} certifications.`);
md.push("");
md.push("## Shared skills (every role)");
md.push("");
for (const sName of shared) md.push(`- ${sName}`);
for (const p of practices) {
  md.push("");
  md.push(`## ${p.name}`);
  for (const r of p.roles) {
    md.push("");
    md.push(`### ${r.name}${r.description ? `: ${r.description}` : ""}`);
    md.push("");
    for (const sName of r.skills ?? []) md.push(`- ${sName}`);
    const recCerts = certs.filter((c) => c.roles?.includes(r.slug));
    if (recCerts.length) md.push(`- *Recommended certifications:* ${recCerts.map((c) => c.name).join("; ")}`);
  }
}
md.push("");
md.push("## Certifications (all marked as needing verification)");
md.push("");
md.push("| Name | Issuer | Code | Tier | Linked roles |");
md.push("|---|---|---|---|---|");
for (const c of [...certs].sort((a, b) => (a.display_priority ?? 100) - (b.display_priority ?? 100))) {
  md.push(`| ${c.name} | ${c.issuer} | ${c.code ?? ""} | ${c.tier} | ${(c.roles ?? []).join(", ") || "all (baseline)"} |`);
}
